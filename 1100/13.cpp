void solve() {
    int n;  cin>>n;
    vector<ll>v(n);
    for(auto &x:v)  cin>>x;
    ll ans=0;
    for(int i=0;i<n/2;i++){
        ans=__gcd(ans, abs(v[i]-v[n-i-1]));
    }
    cout<<ans<<endl;
}

